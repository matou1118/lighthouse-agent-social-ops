"""意向分类：从帖子里判断「谁想办卡 / 谁想装宽带」，并排除同行。

被 `tieba.py` 和 `leads.py` 共用 —— 判断逻辑只写一套。
（见 `库/业务流.md` 维护约定：不要把同类判断散在各脚本里各写一套。）

为什么要分类
------------
一堆「求推荐」里混着一条「绵阳涪城能装吗」，**后者才是能成交的人**。
分类不是为了好看，是为了排序 —— 先回能动销的。

黑话（识别用，不是生产用）
--------------------------
贴吧用 `LT/DX/YD` 指运营商，`绿泡泡/加V` 指微信。工具**认得**它们，
是为了不漏掉真人；工具**不提供**「把微信写成绿泡泡」的转换 ——
平台 AI 已能识别这些变体（2025-2026 多方报道），写了没用还多一条违规记录。

同行过滤
--------
卡商帖和真人求助混在一起。卡商信号很稳定：短链、返点、平台名、模板文案。
**过滤掉它们，剩下的才是客户。**
"""
from __future__ import annotations

import re

# ── 类别表：类别名 → (权重, 正则) ────────────────────────────────────
#: 权重 = 意向强度。3 = 可能直接成交，1 = 只是提到了。
#: 分数是各命中类别权重之和，用于排序。
类别: dict[str, tuple[int, str]] = {
    # 明确在求：最直接的信号
    "求推荐": (3, r"(求推荐|推荐个|推荐一|有没有.{0,6}卡|求个|求张|求一|求私|求带|求问|求教|大哥|大佬|佬|想办|想装|想换|打算办|准备办)"),
    # 携号转网 = 已在决策，转化率高
    "携转换网": (3, r"(携转|携号转网|转网|换网|换卡|转套餐|保号|不换号)"),
    # 宽带装机：本地业务主战场
    "宽带装机": (3, r"(宽带|能装|能不能装|覆盖|装机|报装|光猫|千兆|移机|续费|测速|信号|网速|智慧沃家|沃家|装网|拉网)"),
    # 在比价：有需求但还在挑
    "问资费": (2, r"(月租|多少钱|价格|资费|收费|贵不贵|便宜|划算|双不限|三不限|结转|强充|大流量|多少G|几个G|流量够|套餐)"),
    # 只是提到了某家：弱信号，最常见，也最容易被同行命中
    "指名运营商": (1, r"(?i)(联通|移动|电信|广电|(?<![A-Za-z])LT(?![A-Za-z])|(?<![A-Za-z])YD(?![A-Za-z])"
                   r"|(?<![A-Za-z])DX(?![A-Za-z])|192|王卡|宝卡|冰激凌|冰淇淋|星卡|花卡|无忧卡|沃派)"),
}

#: 求助/求购语气。**判「是不是意向」靠它，不靠话题词。**
#:
#: 这是被实测逼出来的：在「四川联通吧」里，每个帖子都提「联通」，
#: 单看话题词会命中 150+ 条 —— 全是噪声。真正的信号是**他在问/在求**，
#: 而不是他提到了业务名。卖卡帖写「绵阳宽带安装」是广告，不是客户；
#: 用户写「绵阳宽带能装吗」才是。
求助 = re.compile(
    r"(求|想办|想装|想换|想买|想要|想携|想转|想用|想搞|想弄|要办|要装|"
    r"准备办|打算办|打算装|推荐|有没有|能不能|可不可以|行不行|靠不靠谱|靠谱不|"
    r"怎么|咋|多少|哪家|哪个|哪里|多久|如何|值得|"
    r"[?？]|[吗呢][。！…]*$)"
)

#: 现役大流量卡命名规律：地区/季节/动物 + 卡（悟空卡、乐山卡、追月卡…）。
#: 这条能抓到词表都没列的新卡名 —— 比死词表活得久。
卡名 = re.compile(r"(联通|LT|联|电信|DX|移动|YD).{0,6}[\u4e00-\u9fa5]{1,4}卡", re.I)

#: 本地信号：绵阳及所属县市。命中说明这人**能服务**。
本地 = re.compile(r"(绵阳|涪城|游仙|安州|江油|三台|盐亭|梓潼|北川|平武)")

# ── 同行标记（高精度：宁可漏，不可误杀真人）────────────────────────
#: 只收卡商**独有**的信号。「上车」「神车」这类不能收 —— 真人也会说。
同行标记: dict[str, str] = {
    "短链": r"(https?://|t\.cn|url\.cn|dwz\.|短链|点击链接|链接办理)",
    "返佣": r"(返点|返佣|佣金|aff|分销|提成|吃佣金|自己吃)",
    "号卡平台": r"(172号卡|号卡网|卡世界|敢探号|紫鸟|林夕号卡|卡多多|靓号王卡|掌上微厅)",
    "招代理": r"(招代理|招下家|一手货源|长期供应|全国发货|大量出|批发|货源)",
    "模板文案": r"(手慢无|拿通道|扫码办理|在线办理|免费领取|包邮到家)",
}

#: 联系方式（不是违规判定，是「这条已带钩子」的提示）
联系方式 = re.compile(r"(?i)(绿泡泡|绿泡|泡泡|加\s*V|(?<![A-Za-z])VX(?![A-Za-z])|(?<![A-Za-z])WX(?![A-Za-z])"
                    r"|薇|威信|微我|私我|滴滴|戳我|电联|留号|企鹅|扣扣|QQ群|微信号)")

#: 水楼/练级楼。这类帖回复量极大但不是客户 —— 实测「本吧练级大楼」2497 回复，
#: 里面随便一句带「求」就会命中，必须整帖排除。
水楼 = re.compile(r"(练级|水楼|水帖|灌水|签到楼|盖楼|盖楼|刷经验|升级楼|水经验|每日签到)")


def 是水楼(text: str) -> bool:
    return bool(水楼.search(text))


#: 卖家痕迹：作者在**卖**，不是买。（「闲置想出」「转让一张」）
#: 实测噪声里混着「我有一张闲置了 想出 同款套餐」这类 —— 是同行/黄牛，不是客户。
卖家 = re.compile(r"(闲置|想出|出一张|出个|出张|转让|出手|甩卖|低价出|有人要吗|谁要|处理掉)")


def 是卖家(text: str) -> bool:
    return bool(卖家.search(text))


def 分类(text: str) -> list[str]:
    """命中的类别，按权重降序。没有则返回空表。"""
    hits = [(w, name) for name, (w, pat) in 类别.items() if re.search(pat, text)]
    hits.sort(reverse=True)
    return [name for _, name in hits]


def 是否同行(text: str) -> list[str]:
    """命中的同行标记。**空表 = 疑似真人。**"""
    return [name for name, pat in 同行标记.items() if re.search(pat, text)]


def 有联系方式(text: str) -> bool:
    return bool(联系方式.search(text))


def 是本地(text: str) -> bool:
    return bool(本地.search(text))


def 分数(text: str) -> int:
    """意向强度总分。命中卡名额外 +1（指名了具体产品）。"""
    s = sum(类别[name][0] for name in 分类(text))
    if 卡名.search(text):
        s += 1
    return s


def 分析(text: str) -> dict:
    """一次算完，给调用方用。"""
    return {
        "类别": 分类(text),
        "分数": 分数(text),
        "求助": 求购(text),
        "同行": 是否同行(text),
        "联系方式": 有联系方式(text),
        "本地": 是本地(text),
    }


def 是意向(text: str) -> bool:
    """值得提醒吗？

    **必须同时满足**：在问/在求（`求助`）+ 话题相关（命中类别）
    + 不是同行 + 不是水楼 + 不是卖家。
    只看话题词会命中整个吧 —— 见 `求助` 的注释。
    """
    return (bool(分类(text)) and bool(求助.search(text))
            and not 是否同行(text) and not 是水楼(text) and not 是卖家(text))


def 求购(text: str) -> bool:
    return bool(求助.search(text))


# ── 自检 ─────────────────────────────────────────────────────────────
def _demo() -> None:
    """跑一遍代表性样本。任何一条判错，说明逻辑坏了。"""
    # 真人求助（黑话写法）—— 必须能识别
    正例 = [
        ("求个LT大流量卡，月租30以内", ["求推荐", "指名运营商"]),
        ("绵阳涪城这边YD宽带能装吗", ["宽带装机", "指名运营商"]),
        ("想携转，现在用的DX太贵了", ["携转换网", "指名运营商"]),
        ("四川联通悟空卡怎么样，有没有坑", ["指名运营商"]),
        ("求推荐个19元月租的卡", ["求推荐", "问资费"]),
    ]
    for 文本, 应交 in 正例:
        got = 分类(文本)
        for c in 应交:
            assert c in got, f"{文本!r} 应命中 {c}，实际 {got}"
        assert 是意向(文本), f"{文本!r} 应判为意向"
        print(f"  ✅ {文本[:20]:22} → {got}")

    # 同行广告 —— 必须被过滤
    同行例 = [
        "联通悟空卡39元550G 点击链接办理 t.cn/abc",
        "招代理，一手货源，返点高，加V详聊",
        "172号卡平台，全国发货，手慢无",
        "卡世界号卡推广，扫码办理包邮到家",
    ]
    for 文本 in 同行例:
        assert 是否同行(文本), f"同行帖未识别: {文本!r}"
        assert not 是意向(文本), f"同行帖被误判为意向: {文本!r}"
        print(f"  🚫 {文本[:20]:22} → {是否同行(文本)}")

    # 干扰项：有词但非真人（不能因为一个字就报警）
    assert not 是否同行("我学到了，谢谢分享")
    assert 分类("沙发") == [], "纯寒暄不该命中任何类别"

    # ★ 实测逼出来的反例：卖卡帖有话题词但**没有求助语气**，必须排除。
    #   这几个都在绵阳联通吧真实出现过，曾经让单吧命中 150+ 条。
    卖帖 = [
        "绵阳宽带安装",
        "丢一张绵阳归属地带熊猫卡",
        "绵阳归属地联通号段一三一五叭叭叭",
        "专业代办联通宽带，绵阳各区均可",
    ]
    for 文本 in 卖帖:
        assert not 是意向(文本), f"卖卡帖被误判为意向: {文本!r}"
        print(f"  ⚪ {文本[:20]:22} → 非意向（有话题无求助）")

    # 反向：真人求助必须命中
    真例 = [
        "绵阳新皂镇联通信号如何？急",
        "绵阳涪城联通宽带还能装吗",
    ]
    for 文本 in 真例:
        assert 是意向(文本), f"真人求助漏判: {文本!r}"
        print(f"  ✅ {文本[:20]:22} → {分类(文本)}")

    # 本地信号
    assert 是本地("绵阳江油能装吗") and not 是本地("成都能装吗")
    # 卡名正则
    assert 卡名.search("四川联通悟空卡怎么样")
    assert 卡名.search("LT乐山卡")

    print("  自检全部通过")


if __name__ == "__main__":
    _demo()
