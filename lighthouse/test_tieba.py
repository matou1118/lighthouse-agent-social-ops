"""tieba.py / 意向.py 的纯逻辑测试（不联网）。

跑法：python test_tieba.py
重点不是覆盖率，是**把实测踩过的坑钉住** —— 每个 assert 都对应一次真实误判。
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

import 意向
import tieba

通过 = 0


def 断言(条件, 说明=""):
    global 通过
    assert 条件, f"❌ {说明}"
    通过 += 1
    print(f"  ✅ {说明}")


# ── 1. 链接格式 ──────────────────────────────────────────────────────
print("\n[1] 贴吧链接")
断言(tieba.贴链接(123) == "https://tieba.baidu.com/p/123", "帖子链接")
断言(tieba.贴链接(123, 456) == "https://tieba.baidu.com/p/123?pid=456#456", "楼层锚点链接")

# ── 2. 意向判定：真人 vs 卖卡 vs 同行 vs 水楼 ──────────────────────────
print("\n[2] 意向判定（每条都对应一次真实误判）")

# 真人求助 —— 必须命中
断言(意向.是意向("帮我查下我家能装宽带不？能的话我转网办理一下"), "真人求助命中")
断言(意向.是意向("绵阳涪城联通宽带还能装吗"), "本地求助命中")
断言(意向.是意向("求个LT大流量卡，月租30以内"), "黑话求助命中")

# 卖卡帖：有话题词但**没有求助语气** → 排除（实测曾让单吧命中 300+）
断言(not 意向.是意向("绵阳宽带安装"), "卖卡广告排除（无求助）")
断言(not 意向.是意向("丢一张绵阳归属地带熊猫卡"), "卖卡帖排除")
断言(not 意向.是意向("绵阳归属地联通号段一三一五叭叭叭"), "号段广告排除")

# 同行：短链/返佣/平台名 → 排除
断言(not 意向.是意向("联通悟空卡39元550G 点击链接办理 t.cn/abc"), "短链同行排除")
断言(not 意向.是意向("招代理，一手货源，返点高，加V详聊"), "返佣同行排除")
断言(not 意向.是意向("172号卡平台，全国发货，手慢无"), "号卡平台排除")

# 水楼：练级大楼 2497 回复曾整帖误命中
断言(not 意向.是意向("本吧练级大楼"), "水楼排除")
断言(意向.是水楼("本吧练级大楼 每日签到"), "水楼识别")

# 卖家：作者在卖，不是买
断言(not 意向.是意向("我有一张闲置了 想出 同款套餐，多少钱合适"), "卖家帖排除")
断言(意向.是卖家("转让一张129套餐宽带"), "卖家识别")

# 分数：卖卡帖分数低，真客户分数高
断言(意向.分数("求推荐个19元月租的卡") >= 5, "真客户分数够高")
断言(意向.分数("绵阳宽带安装") <= 4, "卖卡帖分数偏低")

# ── 3. 本地信号 ──────────────────────────────────────────────────────
print("\n[3] 本地信号")
for 地名 in ["绵阳", "涪城", "游仙", "安州", "江油", "三台", "盐亭", "梓潼", "北川", "平武"]:
    断言(意向.是本地(f"{地名}能装吗"), f"识别 {地名}")
断言(not 意向.是本地("成都武侯区能装吗"), "成都不是本地")

# ── 4. 增量：同一 tid 不重复入账 ─────────────────────────────────────
print("\n[4] 增量去重（判定逻辑）")
条目 = tieba.判定("求个联通卡", tid=1, pid=None, 吧="测试吧", 作者="张三", 回复量=0)
断言(条目["类别"] and 条目["求助"], "条目带类别和求助标记")
断言(tieba.是意向(条目), "条目判为意向")
断言(条目["链接"] == "https://tieba.baidu.com/p/1", "条目带链接")

库 = {}
key = f"t{条目['tid']}"
库[key] = 条目
断言(key in 库 and len(库) == 1, "首次入库")
# 第二次同样的 tid 不再新增（模拟扫描逻辑）
已存在 = key in 库
断言(已存在, "第二次扫描识别为已存在，不重复")

# ── 5. 状态流转 ──────────────────────────────────────────────────────
print("\n[5] 状态流转")
with tempfile.TemporaryDirectory() as d:
    原意向, 原状态 = tieba.意向文件, tieba.状态文件
    tieba.意向文件 = Path(d) / "意向.json"
    tieba.状态文件 = Path(d) / "状态.json"
    try:
        tieba.写(tieba.意向文件, {"t1": 条目})
        断言(tieba.记阶段("t1", "已回复") == 0, "记阶段成功")
        状态 = tieba.读(tieba.状态文件, {})
        断言(状态["t1"]["阶段"] == "已回复", "阶段写入正确")
        断言(tieba.记阶段("不存在", "已回复") == 1, "未知 id 返回错误码")
    finally:
        tieba.意向文件, tieba.状态文件 = 原意向, 原状态

print(f"\n{'='*40}\n{通过} 项全部通过\n{'='*40}")
